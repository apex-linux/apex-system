//! `apexctl boot repair-grub`: rebuilds `/boot/grub2/grub.cfg` exactly as bootupd's
//! `grubconfigs::install` does, since no bootupctl verb rewrites it on a static-config system.

use std::ffi::OsString;
use std::fmt::Write as _;
use std::fs::{self, File, OpenOptions};
use std::io::{self, Write as _};
use std::os::unix::fs::OpenOptionsExt as _;
use std::path::{Path, PathBuf};

use apex_boot::checks::grub_cfg::{self, MarkerError};

use crate::render::unified_diff;

pub const STATIC_DIR: &str = "usr/lib/bootupd/grub2-static";
pub const PRE_CFG: &str = "grub-static-pre.cfg";
pub const DROPIN_DIR: &str = "configs.d";
pub const HEADER: &str = "# Generated by bootupd / do not edit\n\n";
pub const GRUB_DIR: &str = "boot/grub2";
pub const GRUB_CFG: &str = "grub.cfg";
pub const BACKUP: &str = "grub.cfg.apex-bak";
pub const LOADER_ENTRIES: &str = "boot/loader/entries";
pub const MODE: u32 = 0o600;

#[derive(Debug, thiserror::Error)]
pub enum RepairError {
    #[error("cannot read {}", path.display())]
    Read { path: PathBuf, source: io::Error },
    #[error("cannot write {}", path.display())]
    Write { path: PathBuf, source: io::Error },
    #[error("{} is not valid UTF-8", path.display())]
    NotUtf8 { path: PathBuf },
    #[error(
        "no boot entry in {} names an ostree deployment under {}; mount the system's root \
         there and its boot partition on its boot directory",
        entries.display(),
        root.display()
    )]
    NoDeployment { entries: PathBuf, root: PathBuf },
    #[error("refusing to write the rebuilt grub.cfg, nothing was changed: {0}")]
    Marker(#[from] MarkerError),
}

fn read_error(path: &Path) -> impl FnOnce(io::Error) -> RepairError + '_ {
    |source| RepairError::Read {
        path: path.to_owned(),
        source,
    }
}

fn write_error(path: &Path) -> impl FnOnce(io::Error) -> RepairError + '_ {
    |source| RepairError::Write {
        path: path.to_owned(),
        source,
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Layout {
    pub static_dir: PathBuf,
    pub grub_dir: PathBuf,
}

impl Layout {
    pub fn host() -> Self {
        Self::at(Path::new("/"), Path::new("/"))
    }

    fn at(deployment: &Path, root: &Path) -> Self {
        Self {
            static_dir: deployment.join(STATIC_DIR),
            grub_dir: root.join(GRUB_DIR),
        }
    }

    /// A system mounted from a live USB: the static configs come from the deployment GRUB
    /// boots by default, the entry with the highest `version`.
    pub fn sysroot(root: &Path) -> Result<Self, RepairError> {
        let entries = root.join(LOADER_ENTRIES);
        let no_deployment = || RepairError::NoDeployment {
            entries: entries.clone(),
            root: root.to_owned(),
        };
        let mut default: Option<(u64, String)> = None;
        for entry in fs::read_dir(&entries).map_err(|_| no_deployment())? {
            let path = entry.map_err(read_error(&entries))?.path();
            if path.extension().is_none_or(|ext| ext != "conf") {
                continue;
            }
            let text = fs::read_to_string(&path).map_err(read_error(&path))?;
            if let Some(found) = bls_deployment(&text)
                && default
                    .as_ref()
                    .is_none_or(|(version, _)| found.0 > *version)
            {
                default = Some(found);
            }
        }
        let (_, ostree) = default.ok_or_else(no_deployment)?;
        let deployment = resolve_inside(root, &ostree).ok_or_else(no_deployment)?;
        Ok(Self::at(&deployment, root))
    }

    pub fn grub_cfg(&self) -> PathBuf {
        self.grub_dir.join(GRUB_CFG)
    }

    pub fn backup(&self) -> PathBuf {
        self.grub_dir.join(BACKUP)
    }
}

fn bls_deployment(entry: &str) -> Option<(u64, String)> {
    let field = |key: &str| {
        entry.lines().find_map(|line| {
            let (name, value) = line.trim().split_once(char::is_whitespace)?;
            (name == key).then(|| value.trim())
        })
    };
    let version = field("version")?.parse().ok()?;
    let ostree = field("options")?
        .split_whitespace()
        .find_map(|arg| arg.strip_prefix("ostree="))?;
    Some((version, ostree.to_owned()))
}

/// ostree's `boot.N` links are relative; one that leaves the mounted root is refused rather
/// than followed into the live system.
fn resolve_inside(root: &Path, target: &str) -> Option<PathBuf> {
    let root = root.canonicalize().ok()?;
    let resolved = root
        .join(target.trim_start_matches('/'))
        .canonicalize()
        .ok()?;
    (resolved.starts_with(&root) && resolved.is_dir()).then_some(resolved)
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Rebuilt {
    pub text: String,
    pub dropins: Vec<String>,
}

pub fn rebuild(static_dir: &Path) -> Result<Rebuilt, RepairError> {
    let read = |path: &Path| fs::read_to_string(path).map_err(read_error(path));
    let mut text = String::from(HEADER);
    text.push_str(&read(&static_dir.join(PRE_CFG))?);
    let dropin_dir = static_dir.join(DROPIN_DIR);
    let mut names: Vec<OsString> = fs::read_dir(&dropin_dir)
        .and_then(|entries| entries.map(|e| e.map(|e| e.file_name())).collect())
        .map_err(read_error(&dropin_dir))?;
    names.sort();
    let mut dropins = Vec::new();
    for name in names {
        let path = dropin_dir.join(&name);
        let name = name
            .into_string()
            .map_err(|_| RepairError::NotUtf8 { path: path.clone() })?;
        #[expect(
            clippy::case_sensitive_file_extension_comparisons,
            reason = "bootupd matches the `.cfg` suffix case-sensitively"
        )]
        if !name.ends_with(".cfg") {
            continue;
        }
        let body = read(&path)?;
        let _ = write!(text, "\n### BEGIN {name} ###\n{body}### END {name} ###\n");
        dropins.push(name);
    }
    grub_cfg::scan(&text)?;
    Ok(Rebuilt { text, dropins })
}

pub fn read_current(layout: &Layout) -> Result<Option<Vec<u8>>, RepairError> {
    let path = layout.grub_cfg();
    match fs::read(&path) {
        Ok(bytes) => Ok(Some(bytes)),
        Err(error) if error.kind() == io::ErrorKind::NotFound => Ok(None),
        Err(error) => Err(read_error(&path)(error)),
    }
}

pub fn diff(layout: &Layout, current: Option<&[u8]>, rebuilt: &Rebuilt) -> String {
    let shown = layout.grub_cfg().display().to_string();
    let (old, old_label) = match current {
        Some(bytes) => (String::from_utf8_lossy(bytes).into_owned(), shown.clone()),
        None => (String::new(), "/dev/null".to_owned()),
    };
    unified_diff(
        &old,
        &rebuilt.text,
        &old_label,
        &format!("{shown} (rebuilt)"),
    )
}

/// Writes only `grub.cfg` and its backup, each through a 0600 temporary file renamed into
/// place; `flush` runs last, for the freeze and thaw GRUB's journal-less reader needs.
pub fn write(
    layout: &Layout,
    current: Option<&[u8]>,
    rebuilt: &Rebuilt,
    flush: impl FnOnce(&Path),
) -> Result<Option<PathBuf>, RepairError> {
    let backup = match current {
        Some(bytes) => {
            write_atomic(&layout.grub_dir, BACKUP, bytes)?;
            Some(layout.backup())
        }
        None => None,
    };
    write_atomic(&layout.grub_dir, GRUB_CFG, rebuilt.text.as_bytes())?;
    flush(&layout.grub_dir);
    Ok(backup)
}

fn write_atomic(dir: &Path, name: &str, bytes: &[u8]) -> Result<(), RepairError> {
    let target = dir.join(name);
    let temp = dir.join(format!(".{name}.apex-new"));
    let written = (|| {
        match fs::remove_file(&temp) {
            Err(error) if error.kind() != io::ErrorKind::NotFound => return Err(error),
            _ => {}
        }
        let mut file = OpenOptions::new()
            .write(true)
            .create_new(true)
            .mode(MODE)
            .open(&temp)?;
        file.write_all(bytes)?;
        file.sync_all()?;
        fs::rename(&temp, &target)?;
        File::open(dir)?.sync_all()
    })();
    if written.is_err() {
        let _ = fs::remove_file(&temp);
    }
    written.map_err(write_error(&target))
}

pub fn render_written(layout: &Layout, rebuilt: &Rebuilt, backup: Option<&Path>) -> String {
    let mut text = match backup {
        Some(backup) => format!("Saved the old grub.cfg as {}\n", backup.display()),
        None => format!("There was no {}\n", layout.grub_cfg().display()),
    };
    let _ = writeln!(
        text,
        "Wrote {} from {} ({})",
        layout.grub_cfg().display(),
        layout.static_dir.display(),
        rebuilt.dropins.join(", ")
    );
    text
}

/// The second field of `Uid:` in `/proc/self/status`.
pub fn effective_uid(status: &str) -> Option<u32> {
    status
        .lines()
        .find_map(|line| line.strip_prefix("Uid:"))?
        .split_whitespace()
        .nth(1)?
        .parse()
        .ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_effective_uid_is_the_second_uid_field() {
        let status = "Name:\tapexctl\nUid:\t1000\t0\t0\t0\nGid:\t1000\t1000\t1000\t1000\n";
        assert_eq!(effective_uid(status), Some(0));
        assert_eq!(effective_uid("Uid:\t1000\t1000\t1000\t1000\n"), Some(1000));
        assert_eq!(effective_uid("Name:\tx\n"), None);
    }

    #[test]
    fn a_bls_entry_gives_its_version_and_ostree_path() {
        let entry = "title Apex 45 (ostree:0)\nversion 2\nlinux /ostree/default-abc/vmlinuz\n\
                     options root=UUID=1 rw ostree=/ostree/boot.1/default/abc/0 quiet\n";
        assert_eq!(
            bls_deployment(entry),
            Some((2, "/ostree/boot.1/default/abc/0".to_owned()))
        );
        assert_eq!(bls_deployment("version 2\noptions quiet\n"), None);
        assert_eq!(bls_deployment("options ostree=/x\n"), None);
    }
}
