//! The GRUB environment block, read and edited byte for byte as Fedora's GRUB does
//! (`grub-core/lib/envblk.c`, rhboot/grub2 `fedora-45`). Unlike Ubuntu's GRUB, Fedora's
//! skips only lines starting with `#`, so an empty line starts a variable name.

use std::fmt;
use std::path::Path;

pub const SIGNATURE: &[u8] = b"# GRUB Environment Block\n";

/// `GRUB_ENVBLK_MESSAGE`, which `grub2-editenv create` writes after the signature.
pub const CREATE_WARNING: &[u8] =
    b"# WARNING: Do not edit this file by tools other than grub-editenv!!!\n";

/// `DEFAULT_ENVBLK_SIZE` of `grub2-editenv create`.
pub const BLOCK_SIZE: usize = 1024;

/// The lines stay in block order, not in a map: GRUB edits in place and appends at the end,
/// and duplicate names are legal.
#[derive(Clone, PartialEq, Eq)]
pub struct GrubEnv {
    size: usize,
    lines: Vec<Line>,
}

#[derive(Clone, PartialEq, Eq)]
enum Line {
    Var(Var),
    /// A `#` line. Only the last one may lack its `\n`, when it runs into the padding.
    Other(Vec<u8>),
}

#[derive(Clone, PartialEq, Eq)]
struct Var {
    raw: Vec<u8>,
    stored_name_len: usize,
    name: Vec<u8>,
    value: Vec<u8>,
}

#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum ParseError {
    #[error("environment block is too short ({len} bytes)")]
    TooShort { len: usize },
    #[error("environment block does not start with the GRUB signature")]
    BadSignature,
    #[error("variable at byte {offset} has no '='")]
    MissingEquals { offset: usize },
    #[error("value of the variable at byte {offset} is not terminated")]
    UnterminatedValue { offset: usize },
    /// GRUB would read one variable where `grub2-editenv set` sees two lines, so the block
    /// has no single meaning.
    #[error("variable name at byte {offset} contains a newline")]
    NewlineInName { offset: usize },
}

/// Each case matches a failure of `grub_envblk_set`.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum EditError {
    /// Other names can be misread by `grub2-editenv` (a `=` splits them, a leading `-` is an
    /// option) or by GRUB.
    #[error("invalid GRUB variable name {name:?}")]
    InvalidName { name: String },
    #[error("value of {name} contains a NUL byte")]
    NulInValue { name: String },
    #[error("environment block too small: {needed} bytes needed, {size} available")]
    NoSpace { needed: usize, size: usize },
    #[error("environment block has no newline before its padding; GRUB cannot write to it")]
    Unwritable,
}

#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
#[error("value of GRUB variable {name} is not UTF-8")]
pub struct NotUtf8 {
    pub name: String,
}

#[derive(Debug, thiserror::Error)]
pub enum ReadError {
    #[error("cannot read {path}")]
    Io {
        path: String,
        #[source]
        source: std::io::Error,
    },
    #[error("{path} is not a valid GRUB environment block")]
    Parse {
        path: String,
        #[source]
        source: ParseError,
    },
}

impl GrubEnv {
    /// Exactly what `grub2-editenv <file> create` writes.
    pub fn new() -> Self {
        Self {
            size: BLOCK_SIZE,
            lines: vec![Line::Other(CREATE_WARNING.to_vec())],
        }
    }

    pub fn empty(size: usize) -> Option<Self> {
        (size > SIGNATURE.len()).then(|| Self {
            size,
            lines: Vec::new(),
        })
    }

    /// A block where GRUB's reader stops early is an error, so the result is never a
    /// silently truncated view.
    pub fn parse(bytes: &[u8]) -> Result<Self, ParseError> {
        // GRUB compares against `sizeof (GRUB_ENVBLK_SIGNATURE)`, which counts the NUL.
        if bytes.len() <= SIGNATURE.len() {
            return Err(ParseError::TooShort { len: bytes.len() });
        }
        if !bytes.starts_with(SIGNATURE) {
            return Err(ParseError::BadSignature);
        }
        let end = bytes.len();
        let mut lines = Vec::new();
        let mut p = SIGNATURE.len();
        while p < end {
            if bytes[p] == b'#' {
                let next = find_next_line(bytes, p);
                if next > end {
                    let content = trim_padding(&bytes[p..]);
                    if !content.is_empty() {
                        lines.push(Line::Other(content.to_vec()));
                    }
                    break;
                }
                lines.push(Line::Other(bytes[p..next].to_vec()));
                p = next;
            } else {
                let (var, next) = parse_var(bytes, p)?;
                lines.push(Line::Var(var));
                p = next;
            }
        }
        Ok(Self { size: end, lines })
    }

    pub fn to_bytes(&self) -> Vec<u8> {
        let mut out = Vec::with_capacity(self.size);
        out.extend_from_slice(SIGNATURE);
        for line in &self.lines {
            out.extend_from_slice(line.raw());
        }
        out.resize(self.size, b'#');
        out
    }

    pub fn size(&self) -> usize {
        self.size
    }

    pub fn used(&self) -> usize {
        SIGNATURE.len() + self.lines.iter().map(|l| l.raw().len()).sum::<usize>()
    }

    pub fn free(&self) -> usize {
        self.size - self.used()
    }

    /// As `load_env` reads it: the last line with that name wins.
    pub fn get(&self, name: &str) -> Option<&[u8]> {
        self.vars()
            .filter(|(n, _)| *n == name.as_bytes())
            .map(|(_, v)| v)
            .last()
    }

    pub fn get_str(&self, name: &str) -> Result<Option<&str>, NotUtf8> {
        self.get(name)
            .map(|v| {
                std::str::from_utf8(v).map_err(|_| NotUtf8 {
                    name: name.to_owned(),
                })
            })
            .transpose()
    }

    /// Unescaped, duplicates included, as `grub2-editenv list` prints them.
    pub fn vars(&self) -> impl Iterator<Item = (&[u8], &[u8])> {
        self.lines.iter().filter_map(|line| match line {
            Line::Var(var) => Some((var.name.as_slice(), var.value.as_slice())),
            Line::Other(_) => None,
        })
    }

    /// As `grub_envblk_set` does: the first line with that name is rewritten in place,
    /// otherwise a line is appended. On error the block is unchanged.
    pub fn set(&mut self, name: &str, value: impl AsRef<[u8]>) -> Result<(), EditError> {
        validate_name(name)?;
        let value = value.as_ref();
        if value.contains(&0) {
            return Err(EditError::NulInValue {
                name: name.to_owned(),
            });
        }
        if !self.is_writable() {
            return Err(EditError::Unwritable);
        }
        let line = Var::new(name.as_bytes(), value);
        let used = self.used();
        let position = self.position(name);
        let needed = match position {
            Some(index) => used - self.lines[index].raw().len() + line.raw.len(),
            None => used + line.raw.len(),
        };
        if needed > self.size {
            return Err(EditError::NoSpace {
                needed,
                size: self.size,
            });
        }
        match position {
            Some(index) => self.lines[index] = Line::Var(line),
            None => self.lines.push(Line::Var(line)),
        }
        Ok(())
    }

    /// As `grub_envblk_delete` does: removes the first line with that name, if any.
    pub fn unset(&mut self, name: &str) -> Result<(), EditError> {
        validate_name(name)?;
        if let Some(index) = self.position(name) {
            self.lines.remove(index);
        }
        Ok(())
    }

    /// GRUB finds the free space only after a newline.
    pub fn is_writable(&self) -> bool {
        self.lines
            .last()
            .is_none_or(|line| line.raw().last() == Some(&b'\n'))
    }

    /// `grub_envblk_set` and `grub_envblk_delete` compare the stored name, not the C string.
    fn position(&self, name: &str) -> Option<usize> {
        self.lines.iter().position(|line| match line {
            Line::Var(var) => &var.raw[..var.stored_name_len] == name.as_bytes(),
            Line::Other(_) => false,
        })
    }
}

impl Default for GrubEnv {
    fn default() -> Self {
        Self::new()
    }
}

impl fmt::Debug for GrubEnv {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("GrubEnv")
            .field("size", &self.size)
            .field("used", &self.used())
            .field(
                "vars",
                &self
                    .vars()
                    .map(|(n, v)| {
                        format!(
                            "{}={}",
                            String::from_utf8_lossy(n),
                            String::from_utf8_lossy(v)
                        )
                    })
                    .collect::<Vec<_>>(),
            )
            .finish_non_exhaustive()
    }
}

pub fn read_file(path: &Path) -> Result<GrubEnv, ReadError> {
    let bytes = std::fs::read(path).map_err(|source| ReadError::Io {
        path: path.display().to_string(),
        source,
    })?;
    GrubEnv::parse(&bytes).map_err(|source| ReadError::Parse {
        path: path.display().to_string(),
        source,
    })
}

pub fn is_valid_name(name: &str) -> bool {
    let mut bytes = name.bytes();
    bytes
        .next()
        .is_some_and(|b| b.is_ascii_alphabetic() || b == b'_')
        && bytes.all(|b| b.is_ascii_alphanumeric() || b == b'_')
}

fn validate_name(name: &str) -> Result<(), EditError> {
    if is_valid_name(name) {
        Ok(())
    } else {
        Err(EditError::InvalidName {
            name: name.to_owned(),
        })
    }
}

impl Line {
    fn raw(&self) -> &[u8] {
        match self {
            Line::Var(var) => &var.raw,
            Line::Other(raw) => raw,
        }
    }
}

impl Var {
    /// The line `grub_envblk_set` writes.
    fn new(name: &[u8], value: &[u8]) -> Self {
        let mut raw = Vec::with_capacity(name.len() + 2 + value.len() * 2);
        raw.extend_from_slice(name);
        raw.push(b'=');
        for &byte in value {
            if byte == b'\\' || byte == b'\n' {
                raw.push(b'\\');
            }
            raw.push(byte);
        }
        raw.push(b'\n');
        Self {
            raw,
            stored_name_len: name.len(),
            name: name.to_vec(),
            value: value.to_vec(),
        }
    }
}

/// `find_next_line` from `envblk.c`: past `bytes.len()` when the line has no newline.
fn find_next_line(bytes: &[u8], mut p: usize) -> usize {
    while p < bytes.len() {
        match bytes[p] {
            b'\\' => p += 2,
            b'\n' => break,
            _ => p += 1,
        }
    }
    p + 1
}

/// The body of `grub_envblk_iterate`; also returns the offset of the next line.
fn parse_var(bytes: &[u8], start: usize) -> Result<(Var, usize), ParseError> {
    let stored_name_len = bytes[start..]
        .iter()
        .position(|&b| b == b'=')
        .ok_or(ParseError::MissingEquals { offset: start })?;
    let stored_name = &bytes[start..start + stored_name_len];
    if stored_name.contains(&b'\n') {
        return Err(ParseError::NewlineInName { offset: start });
    }
    let mut value = Vec::new();
    let mut p = start + stored_name_len + 1;
    loop {
        match bytes.get(p) {
            None => return Err(ParseError::UnterminatedValue { offset: start }),
            Some(b'\n') => break,
            Some(b'\\') => {
                match bytes.get(p + 1) {
                    Some(&escaped) => value.push(escaped),
                    None => return Err(ParseError::UnterminatedValue { offset: start }),
                }
                p += 2;
            }
            Some(&byte) => {
                value.push(byte);
                p += 1;
            }
        }
    }
    let var = Var {
        raw: bytes[start..=p].to_vec(),
        stored_name_len,
        name: until_nul(stored_name).to_vec(),
        value: until_nul(&value).to_vec(),
    };
    Ok((var, p + 1))
}

/// What a C string holding these bytes contains.
fn until_nul(bytes: &[u8]) -> &[u8] {
    bytes
        .iter()
        .position(|&b| b == 0)
        .map_or(bytes, |nul| &bytes[..nul])
}

fn trim_padding(bytes: &[u8]) -> &[u8] {
    let keep = bytes.iter().rposition(|&b| b != b'#').map_or(0, |i| i + 1);
    &bytes[..keep]
}

#[cfg(test)]
mod tests {
    use super::*;

    fn block(body: &[u8], size: usize) -> Vec<u8> {
        let mut bytes = SIGNATURE.to_vec();
        bytes.extend_from_slice(body);
        assert!(bytes.len() <= size, "fixture too large");
        bytes.resize(size, b'#');
        bytes
    }

    /// greenboot-rs v0.16.4 `testing_assets/grubenv`, captured on Fedora 39.
    fn fedora_fixture() -> Vec<u8> {
        let mut body = CREATE_WARNING.to_vec();
        body.extend_from_slice(
            b"saved_entry=72c9a2f70064454f91ec38fb40a84d77-6.8.7-200.fc39.x86_64\n\
              boot_success=1\nboot_indeterminate=2\n",
        );
        block(&body, BLOCK_SIZE)
    }

    #[test]
    fn new_matches_grub_editenv_create() {
        let bytes = GrubEnv::new().to_bytes();
        assert_eq!(bytes.len(), 1024);
        assert!(bytes.starts_with(SIGNATURE));
        assert_eq!(
            &bytes[SIGNATURE.len()..SIGNATURE.len() + CREATE_WARNING.len()],
            CREATE_WARNING
        );
        assert!(
            bytes[SIGNATURE.len() + CREATE_WARNING.len()..]
                .iter()
                .all(|&b| b == b'#')
        );
        assert_eq!(GrubEnv::parse(&bytes).unwrap(), GrubEnv::new());
    }

    #[test]
    fn parses_fedora_block() {
        let bytes = fedora_fixture();
        let env = GrubEnv::parse(&bytes).unwrap();
        assert_eq!(env.size(), 1024);
        assert_eq!(env.get_str("boot_success").unwrap(), Some("1"));
        assert_eq!(env.get_str("boot_indeterminate").unwrap(), Some("2"));
        assert_eq!(
            env.get_str("saved_entry").unwrap(),
            Some("72c9a2f70064454f91ec38fb40a84d77-6.8.7-200.fc39.x86_64")
        );
        assert_eq!(env.get("boot_counter"), None);
        assert_eq!(env.vars().count(), 3);
        assert_eq!(env.to_bytes(), bytes);
    }

    #[test]
    fn escapes_backslash_and_newline_like_grub() {
        let mut env = GrubEnv::new();
        env.set("a", "x\\y").unwrap();
        env.set("b", "l1\nl2").unwrap();
        let bytes = env.to_bytes();
        let body = &bytes[SIGNATURE.len() + CREATE_WARNING.len()..];
        assert!(body.starts_with(b"a=x\\\\y\nb=l1\\\nl2\n#"));
        let back = GrubEnv::parse(&bytes).unwrap();
        assert_eq!(back.get("a"), Some(&b"x\\y"[..]));
        assert_eq!(back.get("b"), Some(&b"l1\nl2"[..]));
        assert_eq!(back, env);
    }

    #[test]
    fn a_backslash_escapes_any_byte_when_reading() {
        let env = GrubEnv::parse(&block(b"a=\\x\\#\\=\n", 64)).unwrap();
        assert_eq!(env.get("a"), Some(&b"x#="[..]));
    }

    #[test]
    fn set_rewrites_first_match_in_place_and_appends_new_names() {
        let mut env = GrubEnv::parse(&block(b"a=1\nb=2\na=3\n", 128)).unwrap();
        assert_eq!(env.get("a"), Some(&b"3"[..]));
        env.set("a", "long value").unwrap();
        env.set("c", "4").unwrap();
        assert_eq!(env.to_bytes(), block(b"a=long value\nb=2\na=3\nc=4\n", 128));
        env.unset("a").unwrap();
        assert_eq!(env.to_bytes(), block(b"b=2\na=3\nc=4\n", 128));
        env.unset("missing").unwrap();
        assert_eq!(env.to_bytes(), block(b"b=2\na=3\nc=4\n", 128));
    }

    #[test]
    fn set_fails_without_space_and_leaves_block_unchanged() {
        let mut env = GrubEnv::empty(32).unwrap();
        assert_eq!(env.free(), 7);
        assert_eq!(
            env.set("ab", "1234"),
            Err(EditError::NoSpace {
                needed: 33,
                size: 32
            })
        );
        env.set("ab", "123").unwrap();
        assert_eq!(env.free(), 0);
        let bytes = env.to_bytes();
        assert_eq!(bytes.last(), Some(&b'\n'));
        let mut back = GrubEnv::parse(&bytes).unwrap();
        assert_eq!(back.get("ab"), Some(&b"123"[..]));
        back.set("ab", "1").unwrap();
        assert_eq!(back.to_bytes(), block(b"ab=1\n", 32));
    }

    #[test]
    fn rejects_invalid_names_and_nul_values() {
        let mut env = GrubEnv::new();
        for name in ["", "1a", "a=b", "-a", "a b", "a\n", "é"] {
            assert_eq!(
                env.set(name, "x"),
                Err(EditError::InvalidName {
                    name: name.to_owned()
                })
            );
            assert!(env.unset(name).is_err());
        }
        assert_eq!(
            env.set("a", b"x\0y"),
            Err(EditError::NulInValue {
                name: "a".to_owned()
            })
        );
        assert_eq!(env, GrubEnv::new());
    }

    #[test]
    fn parse_error_cases() {
        assert_eq!(GrubEnv::parse(b""), Err(ParseError::TooShort { len: 0 }));
        assert_eq!(
            GrubEnv::parse(SIGNATURE),
            Err(ParseError::TooShort { len: 25 })
        );
        assert_eq!(
            GrubEnv::parse(b"# GRUB Environment Block\r\n###"),
            Err(ParseError::BadSignature)
        );
        assert_eq!(
            GrubEnv::parse(&block(b"a=1\nnoequals###", 64)),
            Err(ParseError::MissingEquals { offset: 29 })
        );
        let mut unterminated = SIGNATURE.to_vec();
        unterminated.extend_from_slice(b"a=1\nb=never ends");
        assert_eq!(
            GrubEnv::parse(&unterminated),
            Err(ParseError::UnterminatedValue { offset: 29 })
        );
        let mut trailing_escape = SIGNATURE.to_vec();
        trailing_escape.extend_from_slice(b"a=\\");
        assert_eq!(
            GrubEnv::parse(&trailing_escape),
            Err(ParseError::UnterminatedValue { offset: 25 })
        );
        assert_eq!(
            GrubEnv::parse(&block(b"a\nb=1\n", 64)),
            Err(ParseError::NewlineInName { offset: 25 })
        );
    }

    #[test]
    fn skips_comment_lines() {
        let bytes = block(b"# note\n#\na=1\n", 64);
        let env = GrubEnv::parse(&bytes).unwrap();
        assert_eq!(env.vars().collect::<Vec<_>>(), vec![(&b"a"[..], &b"1"[..])]);
        assert_eq!(env.to_bytes(), bytes);
    }

    #[test]
    fn empty_and_cr_lines_are_read_as_fedora_grub_reads_them() {
        let target = b"apex_target=sha256:1111111111111111111111111111111111111111111111111111111111111111\n";
        let mut body = b"\n".to_vec();
        body.extend_from_slice(target);
        body.extend_from_slice(b"apex_counter=2\n");
        assert_eq!(
            GrubEnv::parse(&block(&body, 1024)),
            Err(ParseError::NewlineInName { offset: 25 })
        );
        assert_eq!(
            GrubEnv::parse(&block(b"a=1\n\n", 64)),
            Err(ParseError::MissingEquals { offset: 29 })
        );
        let bytes = block(b"\rbar=2\na=1\n", 64);
        let env = GrubEnv::parse(&bytes).unwrap();
        assert_eq!(
            env.vars().collect::<Vec<_>>(),
            vec![(&b"\rbar"[..], &b"2"[..]), (&b"a"[..], &b"1"[..])]
        );
        assert_eq!(env.get("bar"), None);
        assert_eq!(env.to_bytes(), bytes);
    }

    #[test]
    fn trailing_comment_without_newline_reads_but_is_not_writable() {
        let bytes = block(b"a=1\n# no newline", 64);
        let mut env = GrubEnv::parse(&bytes).unwrap();
        assert_eq!(env.get("a"), Some(&b"1"[..]));
        assert_eq!(env.to_bytes(), bytes);
        assert!(!env.is_writable());
        assert_eq!(env.set("b", "2"), Err(EditError::Unwritable));
        env.unset("a").unwrap();
        assert_eq!(env.to_bytes(), block(b"# no newline", 64));
    }

    #[test]
    fn names_and_values_stop_at_nul_like_c_strings() {
        let env = GrubEnv::parse(&block(b"ab\0c=1\nd=x\0y\n", 64)).unwrap();
        assert_eq!(env.get("ab"), Some(&b"1"[..]));
        assert_eq!(env.get("d"), Some(&b"x"[..]));
        let mut edited = env.clone();
        edited.set("ab", "2").unwrap();
        assert_eq!(edited.vars().count(), 3);
    }

    #[test]
    fn get_str_reports_non_utf8() {
        let env = GrubEnv::parse(&block(b"a=\xff\n", 64)).unwrap();
        assert_eq!(
            env.get_str("a"),
            Err(NotUtf8 {
                name: "a".to_owned()
            })
        );
        assert_eq!(env.get_str("b"), Ok(None));
    }

    #[test]
    fn read_file_reports_path() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("grubenv");
        let err = read_file(&path).unwrap_err();
        assert!(matches!(err, ReadError::Io { .. }));
        std::fs::write(&path, b"this is not a GRUB environment block").unwrap();
        assert!(matches!(
            read_file(&path),
            Err(ReadError::Parse {
                source: ParseError::BadSignature,
                ..
            })
        ));
        std::fs::write(&path, fedora_fixture()).unwrap();
        assert_eq!(
            read_file(&path).unwrap().get_str("boot_success").unwrap(),
            Some("1")
        );
    }

    #[test]
    fn armed_block_snapshot() {
        let mut env = GrubEnv::new();
        env.set(
            "apex_target",
            "sha256:0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef",
        )
        .unwrap();
        env.set("apex_counter", "3").unwrap();
        env.set("apex_ok", "0").unwrap();
        let bytes = env.to_bytes();
        let text = String::from_utf8(bytes.clone()).unwrap();
        let used = env.used();
        insta::assert_snapshot!(format!(
            "{}[{} bytes of '#' padding, block size {}]",
            &text[..used],
            bytes.len() - used,
            bytes.len()
        ));
    }
}
