//! The Rust face of the `io.github.sekirokenjii.Apex.Update1` D-Bus contract.
//!
//! `apex-updated` is the only process that runs bootc. Every other component (`apexctl`,
//! `apex-boot-assess`, and in M2 the Updates app and the session notifier) talks to it
//! through this interface. The authoritative definition is the introspection XML shipped in
//! this crate ([`INTROSPECTION_XML`], installed to `/usr/share/dbus-1/interfaces/`); this crate
//! mirrors it and its tests fail when the two drift apart.
//!
//! What lives here:
//!
//! - well-known names: [`BUS_NAME`], [`OBJECT_PATH`], [`INTERFACE`], [`ERROR_PREFIX`] and the
//!   polkit actions ([`PolkitAction`], contract §1 and §8), with the method each one guards
//!   ([`PolkitAction::guarding`]);
//! - [`Update1Proxy`], the async client proxy generated by [`zbus::proxy`](macro@zbus::proxy);
//! - [`ApexError`], the error replies (`…Update1.Error.<Kind>`), usable both by the daemon as a
//!   method's error type and by clients for matching;
//! - the value types carried by the interface: [`Deployment`] (the `a{sv}` dictionaries),
//!   [`State`], [`Channel`], [`BootVerdict`], [`Change`] and [`ChangeKind`].
//!
//! # Runtime
//!
//! Nothing in this crate spawns tasks, sleeps or names an executor, and the proxy is async
//! only (no blocking proxy is generated), so the same code serves tokio daemons and a `GLib`
//! main-loop GUI. The limit is zbus itself: zbus 5.19 refuses to compile unless one of its
//! backends (`tokio` or `async-io`) is enabled (`compile_error!` in `zbus/src/lib.rs`), so a
//! zbus-based crate cannot be runtime-free at the Cargo level. This crate uses the workspace
//! zbus entry, which selects the `tokio` backend.
//!
//! - **Daemons and CLIs** (tokio `current_thread`): build the [`zbus::Connection`] *inside* the
//!   runtime. zbus then uses tokio and starts no threads of its own.
//! - **`GLib` main loop** (M2 Updates app): enable this crate's `async-io` feature. With both
//!   backends compiled in, zbus 5.19 decides per connection when it is built: tokio if
//!   `tokio::runtime::Handle::try_current()` succeeds, otherwise its own async-io executor
//!   thread. A connection built on the `GLib` main thread therefore needs no tokio runtime, and
//!   the proxy's futures can be driven by `glib::spawn_future_local`. The
//!   `tests/async_io_backend.rs` test runs the proxy on a plain thread-parking executor to
//!   prove it.
//!
//! # Example
//!
//! ```no_run
//! # async fn example() -> Result<(), apex_dbus::ApexError> {
//! use apex_dbus::{ApexError, State, Update1Proxy};
//!
//! let connection = zbus::Connection::system().await?;
//! let proxy = Update1Proxy::new(&connection).await?;
//! if proxy.state().await? == State::Staged {
//!     let staged = proxy.staged().await?;
//!     match proxy.apply(staged.digest.as_deref().unwrap_or_default()).await {
//!         Ok(()) => println!("reboot to finish"),
//!         Err(ApexError::DigestMismatch(message)) => eprintln!("the stage changed: {message}"),
//!         Err(other) => return Err(other),
//!     }
//! }
//! # Ok(())
//! # }
//! ```

